/* ───────────────────────────── 图形基元 ─────────────────────────────
 *  只用五种基本图元描述装备轮廓，够表达火箭 / 飞船 / 空间站 / 探测器的
 *  示意结构，又不用为每个装备写一套手绘 path 字符串。
 *  坐标系就是各自的 viewBox，原点在左上。
 * ─────────────────────────────────────────────────────────────────── */
export type EquipShape =
  /** 矩形（rx = 圆角） */
  | { t: 'r'; x: number; y: number; w: number; h: number; rx?: number }
  /** 多边形，pts 是 [x1,y1, x2,y2, …] 压平数组 */
  | { t: 'p'; pts: number[] }
  /** 圆 / 椭圆（省略 ry 就是正圆） */
  | { t: 'c'; x: number; y: number; r: number; ry?: number }
  /** 线段（dash 给 'd' 画虚线，用于结构分界线） */
  | { t: 'l'; x1: number; y1: number; x2: number; y2: number; dash?: boolean }

/** 一条关键参数 */
export interface EquipFact {
  label: string
  value: string
  /** 有值 = 这条能在官方页面上核对（界面会给 ↗ 链接） */
  src?: { name: string; url: string }
  /** 官方原文（有 src 时才有）。鼠标悬停 / 展开时显示，方便逐字核对 */
  quote?: string
  /** 官方没写、由本站整理的补充说明 */
  note?: string
}

/** 一个部件（可点击的热点） */
export interface EquipPart {
  id: string
  /** 显示名，例如「返回舱」 */
  name: string
  /** 英文 / 型号标注 */
  en?: string
  /** 它是干什么的 —— 展厅的重点就是这个 */
  role: string
  /** 图上的形状 */
  shapes: EquipShape[]
  /** 序号标记的位置（图上的①②③…） */
  hot: { x: number; y: number }
  /** 这个部件自己的关键参数（可选） */
  facts?: EquipFact[]
}

export interface Equipment {
  id: string
  /** 选择器上的短名 */
  short: string
  /** 全称 */
  name: string
  en: string
  /** 归属类别，用于选择器分组标签 */
  family: '运载火箭' | '载人飞船' | '货运飞船' | '空间站' | '月球探测器' | '行星探测器'
  /** 一句话定位 */
  oneLine: string
  /** 用途说明（2~4 句） */
  summary: string
  /** 结构示意图的画布 */
  viewBox: string
  /** 部件（图上热点 + 右侧列表共用） */
  parts: EquipPart[]
  /** 整器关键参数 */
  facts: EquipFact[]
  /** 官方页面（界面上「去官方看这个装备」的出口） */
  sources: { name: string; url: string }[]
}

