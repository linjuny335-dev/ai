/**
 * 把图元转成 SVG 的标签 + 属性。
 * 全部图元共用同一套样式类，配色由 CSS 变量按板块主题决定。
 *
 * ⚠️ 属性名必须是 React 的 camelCase 写法（`strokeDasharray`，不是
 *    `stroke-dasharray`）—— 写成连字符 React 会在控制台报
 *    「Invalid DOM property」并且**属性根本落不到 DOM 上**，虚线会变成实线。
 *    2026-09-21 被 by-foundry-hall.js 的「无脚本报错」这一项抓到。
 */
export function shapeToSvg(s: EquipShape): { tag: string; attrs: Record<string, string> } {
  switch (s.t) {
    case 'r':
      return {
        tag: 'rect',
        attrs: {
          x: String(s.x),
          y: String(s.y),
          width: String(s.w),
          height: String(s.h),
          rx: String(s.rx ?? 0),
        },
      }
    case 'p':
      return { tag: 'polygon', attrs: { points: s.pts.join(' ') } }
    case 'c':
      return {
        tag: 'ellipse',
        attrs: {
          cx: String(s.x),
          cy: String(s.y),
          rx: String(s.r),
          ry: String(s.ry ?? s.r),
        },
      }
    case 'l':
      return {
        tag: 'line',
        attrs: {
          x1: String(s.x1),
          y1: String(s.y1),
          x2: String(s.x2),
          y2: String(s.y2),
          ...(s.dash ? { strokeDasharray: '4 5' } : {}),
        },
      }
  }
}
