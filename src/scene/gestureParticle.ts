/* ============================================================================
 *  手势 → 银河粒子的桥（**张开手掌散开 / 握拳聚拢**）
 * ----------------------------------------------------------------------------
 *  和 `pointer.ts` 同一套做法：一个**普通对象**，每帧被写、每帧被读，
 *  **不进 React state**（否则每帧都要重渲整棵树）。
 *
 *  写方：`ui/gesture/GestureControl.tsx` —— 手势主循环，每帧把内核给的
 *        `spread`（已经过内核低通）写进 `gestureParticle.spread`。
 *  读方：`backgrounds/NebulaField.tsx` —— 在 useFrame 里读它，再做一次惯性平滑
 *        写进 `uSpread` uniform，由顶点着色器把整片银河解体 / 聚拢回原样。
 *
 *  ⚠️ **语义（2026-10-02 反转过一次）**：现在是
 *        spread = 0 → 银河是原本完整的形态（握拳聚拢回来的状态）
 *        spread = 1 → 整片银河解体、星尘向外扩散（张开手掌）
 *     上一版是反的（gather：握拳=收拢成一团、张开=恢复原状），
 *     别再按旧语义写代码。
 *
 *  为什么放在 `scene/` 而不是 `ui/gesture/`：
 *  NebulaField 的既定约定是「不 import 任何 UI 代码」，它是场景层的东西；
 *  放这儿两边都能引，依赖方向也不会倒过来（ui → scene 是允许的）。
 * ========================================================================== */

export const gestureParticle = {
  /**
   * 0 = 原本完整的银河，1 = 整片解体向外扩散。中间值是连续的 ——
   * 手掌张得越开散得越多，握起来就一路聚拢回原样。
   */
  spread: 0,
}

/**
 * 关掉手势 / 组件卸载时调用：把桥归零。
 * 不归零的话，用户在「张着手」的状态下关掉手势，银河会一直卡在散开态。
 */
export function resetGestureParticle(): void {
  gestureParticle.spread = 0
}
