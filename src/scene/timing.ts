/* ============================================================================
 *  统一的帧间隔上限
 * ----------------------------------------------------------------------------
 *  所有随时间推进的动画（转场、旋转、呼吸、颜色插值）都从这里取 dt。
 *
 *  为什么是 0.1 而不是 1/30：
 *    · 上限太小（如 1/30）→ 帧率低于 30fps 时，动画时间会被拉长，
 *      转场在弱设备上一拖就是好几秒，甚至看起来像卡住。
 *    · 上限太大 → 切到后台再切回来时，delta 可能是好几秒，
 *      一帧之内所有东西瞬移。
 *    0.1 秒（≈10fps）是这两者之间的平衡点。
 * ========================================================================== */

export const MAX_DT = 0.1

export const clampDt = (delta: number) => Math.min(delta, MAX_DT)
