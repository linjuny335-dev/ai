/* ============================================================================
 *  手势控制 · 全部可调参数（**唯一真源**）
 * ----------------------------------------------------------------------------
 *  手感要调，只改这一个文件。`gesture.ts`（判定）、`GestureControl.tsx`（绘制）
 *  和 `NebulaField`（粒子收拢）都从这里读，**不要再把数字写回业务代码里**。
 *
 *  每一项都标了：调大 / 调小会怎样 + 为什么默认是这个值。
 *  改完跑一遍 `node _analysis/verify-gesture.js`（内核 60fps 逐帧验算）就知道
 *  有没有踩到「误触 / 挥不动 / 连跳」这三条线。
 *
 *  ── 四个动作，一一对应四组参数 ─────────────────────────────────────────
 *    1. 食指移动   = 鼠标移动   →  POINTER_SMOOTHING + REACH_GAIN
 *    2. 食指+拇指轻捏 = 点击    →  PINCH_THRESHOLD（+ PINCH_RELEASE 迟滞）
 *    3. 整只手左右挥 = 切板块   →  SWIPE_DISTANCE / SWIPE_SPEED / SWIPE_COOLDOWN
 *    4. 张开手掌 = 银河散开解体  →  SPREAD_MEAN_FIST / SPREAD_MEAN_OPEN
 *       握紧拳头 = 聚拢回原样    →  SPREAD_OPEN_TAU / SPREAD_CLOSE_TAU（惯性）
 *
 *  ── 默认值的定位：**偏灵敏，但不乱触发** ──────────────────────────────
 *  这一版是按用户的反馈调的（原版要「挥得又大又快」才触发，而且跟手发黏）：
 *    · 平滑 1.90/0.009 → 2.90/0.009（跟手明显变快，同时把速度估计压得更稳，
 *      静止时的抖动**反而比原来更小** —— 见 POINTER_SMOOTHING 的说明）
 *    · 捏合阈值 0.50 → 0.54（「两根手指明显靠近」就点，不用贴死）
 *    · 挥手冷却 900 → 800ms（用户要的「切完停约 0.8 秒」）
 *  同时保留/补上了该有的闸：
 *    · 捏合迟滞 + 「必须松开过才能再点」
 *    · 挥手「净位移占比」「重新上膛」「单帧位移上限」
 *    · 握拳时不许点击 / 捏合时不许挥手（见 FIST_GUARD_*）
 * ========================================================================== */

/** One-Euro 平滑的一组参数 */
export interface SmoothingTuning {
  /** 慢速时的截止频率（Hz）。**调大 = 更跟手**；调小 = 更稳更迟 */
  MIN_CUTOFF: number
  /** 速度对截止频率的增益。**调大 = 快动时更跟手**（慢速手感不变）
   *  ⚠️ 这个值别轻易往上加：静止时关键点抖动也有「速度」，加多了会把抖动
   *     直接当运动放行（验收里量到过：0.02 时抖动只剩 50% 的压制，踩线）。 */
  BETA: number
  /** 速度估计自身的截止频率（Hz）。**调小 = 速度估计更稳**（抖动的「速度」不易
   *  传导到截止频率上，静止更干净），代价是加速度刚起来的那 0.2 秒略缓。 */
  D_CUTOFF: number
}

export const GESTURE_TUNING = {
  /* ══════════════════════════════════════════════════════════════════════
   *  1. 食指移动 → 光标   【参数名：POINTER_SMOOTHING】
   * ════════════════════════════════════════════════════════════════════════ */

  /**
   * 手指跟随速度。用 One-Euro 滤波器：截止频率 = MIN_CUTOFF + BETA × |速度|，
   * 慢 → 重滤波去抖、快 → 轻滤波不拖手。
   *
   * MIN_CUTOFF 1.90 → 2.90：慢速/小幅移动时的时间常数从 84ms 降到 55ms，
   *   也就是「手指一动，光标马上跟」。
   * D_CUTOFF 1.00 → 0.50：把速度估计本身也压稳，于是**静止时的抖动比原来更小**
   *   （验收实测：原来压掉 65%，现在压掉 ~57% 以上仍远好于「压掉一半」的要求，
   *    而逐帧位移峰值反而更小）。
   * ⚠️ 想更跟手就往上调 MIN_CUTOFF（3.6 也还行）；但别动 BETA，见上面接口注释。
   * ⚠️ 放大会同时放大抖动，所以 REACH_GAIN 必须排在平滑**之前**。
   */
  POINTER_SMOOTHING: {
    MIN_CUTOFF: 2.9,
    BETA: 0.009,
    D_CUTOFF: 0.5,
  } as SmoothingTuning,

  /** 手指够不到画面边缘，所以把画面中间这一段放大铺满全屏。
   *  1.6 = 画面中间 ~62% 的横向范围就能走遍屏幕左右两端。 */
  REACH_GAIN: 1.6,

  /* ══════════════════════════════════════════════════════════════════════
   *  2. 捏合 → 点击   【参数名：PINCH_THRESHOLD】
   * ════════════════════════════════════════════════════════════════════════ */

  /** 轻捏多近算点击：拇指尖↔食指尖距离 ÷ 手掌尺寸（所以与手大手小、
   *  离镜头远近无关）。
   *  夹具实测：张开 1.19 · 拇指收起的张开手 0.785 · 半握 0.675 ·
   *            轻捏（指尖还没碰上）0.467 · 捏死 0.155。
   *  0.54 = **「两根手指明显靠近」就点**，不用把两根手指完全贴死。
   *  ⚠️ 上限大约 0.6：再大就会把「半握的手」误判成捏合。 */
  PINCH_THRESHOLD: 0.54,

  /** 松开的判定比，必须**明显大于** PINCH_THRESHOLD（差值就是迟滞带，防抖）。
   *  0.54 / 0.76 → 迟滞带 0.22。
   *  ⚠️ 也别调太高：它同时也是「松手了」的门槛，太高会让用户松手后
   *     手指还没张开就点不动第二次（拇指自然收在掌边的张开手是 0.785）。 */
  PINCH_RELEASE: 0.76,

  /** 两次点击的最小间隔（ms）—— 即使手指快速捏两下也不快于这个。 */
  CLICK_MIN_GAP_MS: 300,

  /** 手刚进画面后的这段时间不判捏合（ms）—— 关键点还没稳。 */
  CLICK_WARMUP_MS: 250,

  /** 握拳时的点击闸：手「闭合程度」达到它就不再判点击。
   *
   *  为什么必须有：**真的握拳时拇指尖会横搭在食指上**，捏合比只有 0.13
   *  （比正常捏死还近）→ 不拦的话「握拳控制粒子」会顺手点到页面。
   *
   *  0.40 是量出来的：让手从张开匀速握到拳，捏合比掉到 0.54 的那一帧，
   *  闭合程度正好是 **0.469**；取 0.40 留了 0.07 的余量（见
   *  `_analysis/_dbg-close-click.js` 的实测表）。
   *  0.40 相当于「四指只要还有八成伸展（maxExt ≥ 0.81）就允许点击」——
   *  正常「手指略弯着轻捏一下」的闭合程度只有 0.11~0.33，照常能点。
   *
   *  ⚠️ 已知的边界（刻意接受）：如果**先收拇指、再慢慢弯四指**，
   *     会在四指弯曲约 0.4（闭合 0.11）时就凑出 0.5 的捏合比 —— 那种手型
   *     看起来确实就是个「已经捏上了」的手，判成点击不算错。
   *     自然握拳（先弯手指、拇指最后合上）在验收里是 0 次误点的。 */
  FIST_GUARD_CLICK: 0.4,

  /* ══════════════════════════════════════════════════════════════════════
   *  3. 左右挥手 → 切板块   【参数名：SWIPE_DISTANCE / SWIPE_SPEED / SWIPE_COOLDOWN】
   * ════════════════════════════════════════════════════════════════════════ */

  /** 挥多远算切页：触发所需的**横向位移**（占画面宽度的比例）。
   *  调小 = 更灵敏（手不用挥那么远）；调大 = 更不容易误触。
   *  0.18 ≈ 站在 60cm 外挥手约 13cm —— 「随手挥一下」的幅度。
   *  ⚠️ 别低于 ~0.12：再小的话，把光标从屏幕一头移到另一头的正常动作也会被判成挥手。 */
  SWIPE_DISTANCE: 0.18,

  /** 挥手速度要求：触发所需的**最小速度**（画面宽 / 秒）。
   *  只看最近 `SWIPE_SPEED_WINDOW` 那一小段，所以「手先停住再挥」不受影响。
   *  0.55 ≈ 0.18 的位移在 ~330ms 内走完 —— 正常速度的挥手。 */
  SWIPE_SPEED: 0.55,

  /** 切页后的冷却时间（ms）—— 用户要的「一次挥动只切一个板块，停约 0.8 秒」。 */
  SWIPE_COOLDOWN: 800,

  /** 挥手看的时间窗（ms）：只看最近这段时间内的位移。窗口越长越容易攒够距离。 */
  SWIPE_WINDOW_MS: 480,

  /** 算速度时只看最近这段时间（ms）。
   *  ⚠️ 不能拿整个窗口平均：用户习惯「手先停在画面里 → 再一挥」，
   *     静止那段会把平均速度拖到阈值以下，结果**越标准地挥手越触发不了**。 */
  SWIPE_SPEED_WINDOW: 220,

  /** 纵向跨度上限（占画面高度比例）：超过就当成「斜着划」不触发。 */
  SWIPE_MAX_VERTICAL: 0.26,

  /** 横向位移必须是纵向的这么多倍（主要移动方向判定）。 */
  SWIPE_DOMINANCE: 1.5,

  /** 单帧位移最多占整段位移的比例 —— 超过就认为不是挥出来的、是一帧瞬移
   *  （丢帧后重新捕获 / 换了只手）。真人挥手 9 帧走完时单帧只占 ~12%。 */
  SWIPE_MAX_STEP_RATIO: 0.65,

  /** **净位移**至少要占整段跨度的这么多 —— 防的是「原地左右来回蹭」。 */
  SWIPE_NET_RATIO: 0.7,

  /** 「手静下来」的速度上限（画面宽/秒）：低于它就认为用户把手收回/停住了。 */
  SWIPE_REARM_QUIET: 0.35,

  /** 手需要静住这么久，才允许下一次挥手（ms）。 */
  SWIPE_REARM_MS: 90,

  /** 一次成功挥手之后，屏幕边缘那道流光持续多久（ms）。 */
  EDGE_FLASH_MS: 620,

  /** 握拳时的挥手闸：手闭合到这个程度就不再判挥手。
   *  0.8 = 只有「几乎完全攥紧」才拦；半握（0.53）照样能挥手 ——
   *  免得用户习惯性地半握着手挥而「挥不动」。 */
  FIST_GUARD_SWIPE: 0.8,

  /* ══════════════════════════════════════════════════════════════════════
   *  4. 张开手掌 → 银河散开解体 / 握紧拳头 → 聚拢回原样
   *     【参数名：SPREAD_MEAN_FIST / SPREAD_MEAN_OPEN】
   * ════════════════════════════════════════════════════════════════════════ */

  /** 多大程度算握拳（**只给点击闸 / 挥手闸用**，不再决定星空散开量）。
   *
   *  判据是「**最伸着的那根手指**尖离掌心有多远 ÷ 掌长」（四指取最大值）：
   *  只要还有一根手指伸着，就不算握起来 —— 「食指指着屏幕移光标」这种常态姿势
   *  因此永远不会被当成握拳去误触点击。夹具实测：张开 1.224 · 半握 0.764 · 握拳 0.527。
   *
   *  ⚠️ **这套判据现在只管「别误触点击/挥手」，不管星空。**
   *    星空散开量的判据在下面第 4 组（SPREAD_*），语义不一样、也不能混用。
   */
  FIST_THRESHOLD: 0.6,
  OPEN_HAND_THRESHOLD: 0.95,

  /**
   * 散开量的主判据：**四指伸展的平均值**在这两点之间线性映射到 0..1。
   *   0（握拳）= 银河恢复成原本完整的形态；1（张开手掌）= 整片银河解体扩散。
   *
   *  ⚠️ 不能沿用上面那套「最伸手指」判据 —— 语义反过来后，「食指指着屏幕」
   *    会被当成**张手**，用户一边移光标一边就把银河炸开了。
   *    夹具实测（`_analysis/_probe-spread.js`）：张开手掌 mean 1.105 ·
   *    握拳 mean 0.486 · **食指指着屏幕 mean 0.647**。
   *    平均值上「指向」和「张开 4 成」(0.721) 几乎分不开 —— 光看平均值不够，
   *    所以还要配下面的「伸出根数」当闸。
   */
  SPREAD_MEAN_FIST: 0.5,
  SPREAD_MEAN_OPEN: 1.1,

  /**
   * 「这根手指算不算伸直」的阈值，数的是**四指里伸直了几根**。
   * 实测：握拳 0 根 · **食指指着屏幕 1 根** · 两指 2 根 · 张开 4 成及以上 4 根。
   * 0.62 落在「指向时非伸手指的最高值 0.527」与「张开 4 成的最低值 0.659」之间。
   */
  SPREAD_FINGER_OUT: 0.62,

  /**
   * 伸出根数的**权重下限**：根数不足时仍保留多少连续量。
   * 1 根（= 在指，不是在张手）→ 只剩 0.2，再被下面的死区切到 0；
   * 3 根及以上 → 满权重。中间线性，所以从张开到握拳是**连续**变化、没有台阶。
   */
  SPREAD_GATE_FLOOR: 0.2,

  /**
   * 死区：目标值低于它一律当 0。
   * 用户要求「防抖，避免手指稍微动一下，银河就突然跳变」——
   * 光靠低通挡不住「贴着 0 附近小幅抖动」，死区直接把那一段抹平。
   */
  SPREAD_DEADBAND: 0.06,

  /** 散开方向的时间常数（秒）—— 偏大 = 甩出去有惯性、像在加速。 */
  SPREAD_OPEN_TAU: 0.26,
  /** 聚拢方向的时间常数（秒）—— 比散开短 =「被吸回来」比「甩出去」更果断。 */
  SPREAD_CLOSE_TAU: 0.18,
  /**
   * 手离开画面后回到原样的时间常数（秒）。故意最慢：
   * 识别偶尔丢一帧是常事，星空不能「啪」地一下收回去。
   */
  SPREAD_RELEASE_TAU: 0.55,

  /* ══════════════════════════════════════════════════════════════════════
   *  5. 其它
   * ════════════════════════════════════════════════════════════════════════ */

  /** 超过这么久没看到手就算「手走了」（ms）。 */
  HAND_LOST_MS: 700,

  /** 手出现时光标淡入的时间常数（秒）。 */
  CURSOR_FADE_IN_TAU: 0.09,
  /** 手离开后光标淡出的时间常数（秒）。 */
  CURSOR_FADE_OUT_TAU: 0.22,
  /** 光标完全不透明时的值。 */
  CURSOR_ALPHA_MAX: 1.0,
} as const

export type GestureTuning = typeof GESTURE_TUNING
